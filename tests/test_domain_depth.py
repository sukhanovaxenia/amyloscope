"""Domain grouping at Pfam depth, and the unannotated bucket.

The omission these pin: ``compute_domain_overlap`` grouped by ``category``, an
abstract vocabulary in which a whole protein family collapses onto two labels,
and residues in NO domain were in no group at all -- so the annotation's
coverage silently became the denominator of the test.

On the FXR1 family a config generated by ``aggressor-wrappers`` carries
``Tudor_FRX1``, ``Agenet``, ``KH_9``, ``KH_1``, ``FXMRP1_C_core`` and
``FXR_C1/C2/C3`` by name; ``categorise()`` maps the first four onto
``rna_binding`` and the rest onto ``default``, and a further 12-30 % of each
chain -- the RGG/low-complexity tract, the exact fraction depending on whether
overlapping Pfam hits are trimmed or dropped -- is in neither. At category depth the test can
only ask "RNA-binding or not", and cannot see that APRs are ~3-fold enriched in
Agenet/Tudor while being essentially absent from the C-terminal domains.
"""

from __future__ import annotations

from dataclasses import dataclass

import pytest

from amyloscope.analysis.domains import (
    UNANNOTATED,
    _domain_key,
    _group_residues,
)


@dataclass
class FakeDomain:
    name: str
    start: int
    stop: int
    category: str


@dataclass
class FakeSpec:
    length: int
    domains: list


#: The human FXR1 architecture, at the two depths.
FXR1 = FakeSpec(
    length=621,
    domains=[
        FakeDomain("Tudor_FRX1", 4, 52, "rna_binding"),
        FakeDomain("Agenet", 62, 116, "rna_binding"),
        FakeDomain("KH_9", 123, 207, "rna_binding"),
        FakeDomain("KH_1", 221, 277, "rna_binding"),
        FakeDomain("KH_1b", 286, 347, "rna_binding"),
        FakeDomain("FXMRP1_C_core", 354, 448, "default"),
        FakeDomain("FXR_C1", 461, 534, "default"),
        FakeDomain("FXR_C3", 554, 620, "default"),
    ],
)


def test_category_depth_collapses_the_architecture() -> None:
    """Eight named domains, two categories. This is the omission."""
    categories = {_domain_key(d, "category") for d in FXR1.domains}
    names = {_domain_key(d, "name") for d in FXR1.domains}
    assert categories == {"rna_binding", "default"}
    assert len(names) == 8


def test_name_depth_separates_domains_that_share_a_category() -> None:
    agenet = _group_residues(FXR1, "Agenet", group_by="name")
    c1 = _group_residues(FXR1, "FXR_C1", group_by="name")
    assert agenet == set(range(62, 117))
    assert c1 == set(range(461, 535))
    assert not (agenet & c1)

    # At category depth both vanish into a pooled label.
    rna = _group_residues(FXR1, "rna_binding", group_by="category")
    assert agenet < rna
    assert len(rna) > len(agenet)


def test_unannotated_is_the_complement() -> None:
    annotated: set[int] = set()
    for d in FXR1.domains:
        annotated |= set(range(d.start, d.stop + 1))
    un = _group_residues(FXR1, UNANNOTATED, group_by="name")
    assert un == set(range(1, FXR1.length + 1)) - annotated
    assert not (un & annotated)


def test_groups_partition_the_sequence_at_both_depths() -> None:
    """With UNANNOTATED present the groups cover every residue exactly once.

    Without it they covered only the annotated fraction -- about 70 % here --
    and the missing 30 % left the test silently.
    """
    for depth in ("name", "category"):
        keys = {_domain_key(d, depth) for d in FXR1.domains} | {UNANNOTATED}
        covered: set[int] = set()
        total = 0
        for k in keys:
            res = _group_residues(FXR1, k, group_by=depth)
            covered |= res
            total += len(res)
        assert covered == set(range(1, FXR1.length + 1))
        # No residue counted twice: these domains do not overlap.
        assert total == FXR1.length


def test_unannotated_is_a_substantial_fraction() -> None:
    """12.4 % for these trimmed coordinates; ~16 % averaged over orthologues,
    and nearer 30 % when overlapping hits are dropped rather than trimmed.
    Whatever the policy, it is far too much to leave out of the denominator."""
    un = _group_residues(FXR1, UNANNOTATED, group_by="name")
    fraction = len(un) / FXR1.length
    assert 0.10 < fraction < 0.20


def test_group_by_is_validated() -> None:
    """Rejected before anything else is touched, so a typo fails loudly."""
    from amyloscope.analysis.domains import compute_domain_overlap

    with pytest.raises(ValueError, match="group_by must be"):
        compute_domain_overlap(None, group_by="pfam")


def test_overlapping_annotations_are_not_double_counted_within_a_group() -> None:
    """Nested domains share residues; a group is a residue SET, not a sum."""
    nested = FakeSpec(
        length=300,
        domains=[
            FakeDomain("outer", 51, 268, "structured_core"),
            FakeDomain("inner", 96, 167, "structured_core"),
        ],
    )
    core = _group_residues(nested, "structured_core", group_by="category")
    assert len(core) == 268 - 51 + 1          # not 218 + 72
    un = _group_residues(nested, UNANNOTATED, group_by="category")
    assert len(core) + len(un) == nested.length
